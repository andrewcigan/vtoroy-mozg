// Название карточки после «исправь»: старая цена или процент в нём не остаются, имя не портится.
import test from "node:test";
import assert from "node:assert/strict";
import { freshTitle } from "./card-title.ts";

const OLD = "Нацбанк снизил ставку рефинансирования до 9,5%.";

void test("единственная величина исправлена и в названии", () => {
  assert.equal(
    freshTitle(
      "Снижение ставки рефинансирования до 9,5%",
      OLD,
      "Ставка рефинансирования — 9,25%.",
    ),
    "Снижение ставки рефинансирования до 9,25%",
  );
  assert.equal(
    freshTitle(
      "Офис в Бресте: аренда от 12 руб./м²",
      "Офис сдаётся от 12 рублей за м2.",
      "Офис сдаётся от 14 рублей за м2.",
    ),
    "Офис в Бресте: аренда от 14 руб./м²",
  );
});

void test("число в имени не трогаем", () => {
  assert.equal(
    freshTitle(
      "Windows 11 25H2",
      "Windows 11 выйдет, цена 10 долларов.",
      "Выйдет, цена 12 долларов.",
    ),
    "Windows 11 25H2",
  );
  assert.equal(
    freshTitle("1984", "Роман 1984, 5 рублей.", "Роман, 7 рублей."),
    "1984",
  );
});

void test("что на что менять неясно — название прежнее", () => {
  assert.equal(
    freshTitle("Скидка 10%", "Скидка 10%.", "Скидка 15%, для своих 20%."),
    "Скидка 10%",
  );
  assert.equal(
    freshTitle("Скидка 10%", "Скидка 10%.", "Скидки больше нет."),
    "Скидка 10%",
  );
  assert.equal(
    freshTitle("Скидка 10%", "Скидка 10%.", "Скидка 10%, до пятницы."),
    "Скидка 10%",
  );
});
